declare
	missing_users text;
	duplicate_user_names text;
	missing_voices text;
	duplicate_voice_names text;
	created_by_count integer;
	already_imported_count integer;
begin
	select string_agg(distinct i.player_name, ', ' order by i.player_name)
	into missing_users
	from _oea_excel_import i
	where not exists (
		select 1
		from public.oea_users u
		where lower(u.name) = lower(i.player_name)
	);

	if missing_users is not null then
		raise exception 'Import OEA bloccato: utenti non trovati in oea_users: %', missing_users;
	end if;

	select string_agg(name, ', ' order by name)
	into duplicate_user_names
	from (
		select lower(u.name) as name
		from public.oea_users u
		join (select distinct lower(player_name) as name from _oea_excel_import) i on i.name = lower(u.name)
		group by lower(u.name)
		having count(*) > 1
	) duplicates;

	if duplicate_user_names is not null then
		raise exception 'Import OEA bloccato: nomi utente duplicati in oea_users: %', duplicate_user_names;
	end if;

	select string_agg(distinct i.voice_name, ', ' order by i.voice_name)
	into missing_voices
	from _oea_excel_import i
	where not exists (
		select 1
		from public.oea_voices v
		where lower(v.name) = lower(i.voice_name)
	);

	if missing_voices is not null then
		raise exception 'Import OEA bloccato: voci non trovate in oea_voices.name: %', missing_voices;
	end if;

	select string_agg(name, ', ' order by name)
	into duplicate_voice_names
	from (
		select lower(v.name) as name
		from public.oea_voices v
		join (select distinct lower(voice_name) as name from _oea_excel_import) i on i.name = lower(v.name)
		group by lower(v.name)
		having count(*) > 1
	) duplicates;

	if duplicate_voice_names is not null then
		raise exception 'Import OEA bloccato: nomi voce duplicati in oea_voices: %', duplicate_voice_names;
	end if;

	select count(*)
	into created_by_count
	from public.oea_users u
	where lower(u.name) = lower('Robby');

	if created_by_count <> 1 then
		raise exception 'Import OEA bloccato: created_by % deve esistere una sola volta in oea_users, trovati %', 'Robby', created_by_count;
	end if;

	select count(*)
	into already_imported_count
	from public.oea_games g
	where g.notes = 'Import Excel OEA: data oea 2.xlsx';

	if already_imported_count > 0 then
		raise exception 'Import OEA bloccato: risultano gia'' presenti % partite con notes = %', already_imported_count, 'Import Excel OEA: data oea 2.xlsx';
	end if;
end $$;

create temp table _oea_created_games (
	game_key integer primary key,
	game_id uuid not null default gen_random_uuid(),
	played_at date not null
) on commit drop;

insert into _oea_created_games (game_key, played_at)
select distinct game_key, played_at
from _oea_excel_import
order by game_key;

insert into public.oea_games (id, played_at, on_record, created_by, notes)
select
	cg.game_id,
	cg.played_at,
	true,
	(select u.id from public.oea_users u where lower(u.name) = lower('Robby') limit 1),
	'Import Excel OEA: data oea 2.xlsx'
from _oea_created_games cg
order by cg.game_key;

insert into public.oea_game_players (game_id, user_id, player_order)
select distinct
	cg.game_id,
	u.id,
	i.player_order
from _oea_excel_import i
join _oea_created_games cg on cg.game_key = i.game_key
join public.oea_users u on lower(u.name) = lower(i.player_name)
order by cg.game_id, i.player_order;

insert into public.oea_scores (game_id, user_id, voice_id, score)
select
	cg.game_id,
	u.id,
	v.id,
	i.score
from _oea_excel_import i
join _oea_created_games cg on cg.game_key = i.game_key
join public.oea_users u on lower(u.name) = lower(i.player_name)
join public.oea_voices v on lower(v.name) = lower(i.voice_name)
order by i.game_key, i.player_order, v.sort_order;

