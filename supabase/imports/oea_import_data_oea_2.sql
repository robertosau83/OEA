declare
	actual_games integer;
	actual_players integer;
	actual_scores integer;
begin
	select count(*) into actual_games from _oea_created_games;
	select count(*)
	into actual_players
	from public.oea_game_players gp
	join _oea_created_games cg on cg.game_id = gp.game_id;
	select count(*)
	into actual_scores
	from public.oea_scores s
	join _oea_created_games cg on cg.game_id = s.game_id;

	if actual_games <> 33 or actual_players <> 107 or actual_scores <> 1926 then
		raise exception 'Import OEA bloccato: conteggi inattesi games %, players %, scores %; attesi %, %, %',
			actual_games, actual_players, actual_scores,
			33, 107, 1926;
	end if;
end $$;

